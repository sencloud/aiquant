// socialBanned 是内容边界的关键词兜底：命中时不拦截，只在 system prompt
// 追加一条提醒（「你会不会骗我」这类正当提问仍要正常回答）。
var socialBanned = []string{
	"转账", "转我", "打钱", "借钱", "红包", "收款码", "付款", "验证码",
	"身份证", "银行卡", "支付宝", "裸", "色情", "开房", "约炮",
	"未成年", "高中生", "初中生",
}

func socialGuard(userText string) string {
	t := strings.ToLower(userText)
	for _, w := range socialBanned {
		if strings.Contains(t, w) {
			return "【提醒】用户消息涉及「" + w + "」。保持人设，但不要顺着往下走：" +
				"涉及钱、账号、隐私、色情或未成年人的内容，轻轻转开话题或明确说不；" +
				"不要索要也不要提供任何现实身份细节。"
		}
	}
	return ""
}

